-- TEST — devuelve TABLA: el check existe, EXENTA a los es_pase, y la matemática de
-- fecha es correcta (día siguiente bloquea; mismo día permite).
-- ════════════════════════════════════════════════════════════════════════════
SELECT
  'reserva vigencia exenta day pass' AS prueba,
  pg_get_functiondef('reservar_clase_atomic(uuid, integer, text, text)'::regprocedure)
    ILIKE '%CLASE_FUERA_DE_VIGENCIA%'                       AS tiene_check,
  pg_get_functiondef('reservar_clase_atomic(uuid, integer, text, text)'::regprocedure)
    ILIKE '%NOT COALESCE(v_es_pase%'                        AS exenta_daypass,
  (date '2026-10-24' > date '2026-10-23')                   AS dia_siguiente_bloquea,
  (NOT (date '2026-10-23' > date '2026-10-23'))             AS mismo_dia_permite;
